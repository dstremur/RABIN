static void copy_tail_cols(rmat_t* dst, const rmat_t* src, u64 c0)
{
  assert(rmat_init(dst, src->rows, src->cols - c0) == RABIN_SUCCESS);
  for (u64 x = 0; x < src->rows; x++) {
    for (u64 y = c0; y < src->cols; y++) {
      assert(rz_copy(RMAT_GET(dst, x, y - c0), RMAT_GET(src, x, y)) ==
             RABIN_SUCCESS);
    }
  }
}

static void check_kernel_image(const rmat_t* A)
{
  const u64 n = A->cols;
  const u64 rank = (A->rows <= A->cols) ? rank_via_mlll(A) : A->rows;
  rmat_t H = {0}, Kpart = {0}, Tpart = {0}, AK = {0}, AT = {0}, Ik = {0};
  u64 p = 0;
  assert(rmat_kernel_image(A, &H, &p) == RABIN_SUCCESS);
  assert(H.rows == n && H.cols == n);
  assert(p == rank);
  assert(is_unimodular(&H));
  const u64 r = n - p;

  // first r columns lie in the kernel and generate the kernel lattice
  assert(rmat_init(&Kpart, n, r) == RABIN_SUCCESS);
  for (u64 x = 0; x < n; x++) {
    for (u64 y = 0; y < r; y++) {
      assert(rz_copy(RMAT_GET(&Kpart, x, y), RMAT_GET(&H, x, y)) ==
             RABIN_SUCCESS);
    }
  }
  if (r > 0) {
    assert(rmat_init(&AK, A->rows, r) == RABIN_SUCCESS);
    assert(rmat_mul(&AK, A, &Kpart) == RABIN_SUCCESS);
    assert(is_zero_mat(&AK));
    rmat_t Kref = {0};
    assert(rmat_kernel(A, &Kref) == RABIN_SUCCESS);
    assert(same_lattice(&Kpart, &Kref));
    rmat_clear(&Kref);
  }

  // last p columns preserve the image lattice
  if (p > 0) {
    copy_tail_cols(&Tpart, &H, r);
    assert(rmat_init(&AT, A->rows, Tpart.cols) == RABIN_SUCCESS);
    assert(rmat_mul(&AT, A, &Tpart) == RABIN_SUCCESS);
    assert(rmat_hermite(&Ik, A) == RABIN_SUCCESS);
    assert(same_lattice(&AT, &Ik));
  }

  rmat_clear(&H);
  rmat_clear(&Kpart);
  rmat_clear(&Tpart);
  rmat_clear(&AK);
  rmat_clear(&AT);
  rmat_clear(&Ik);
}

static void test_kernel_image(void)
{
  {
    rmat_t A = {0};
    build_dep_2x3(&A);
    check_kernel_image(&A);
    rmat_clear(&A);
  }
  {
    rmat_t A = {0};
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    set164(&A, 0, 0, 3);
    set164(&A, 1, 1, 2);
    check_kernel_image(&A);
    rmat_clear(&A);
  }
  {
    rmat_t A = {0};
    assert(rmat_init(&A, 2, 3) == RABIN_SUCCESS);  // zero
    check_kernel_image(&A);
    rmat_clear(&A);
  }
  srand(0x51DF);
  for (int trial = 0; trial < 10; trial++) {
    rmat_t A = {0};
    const u64 m = 3, n = 5;
    assert(rmat_init(&A, m, n) == RABIN_SUCCESS);
    for (u64 x = 0; x < m; x++) {
      for (u64 y = 0; y < n; y++) set164(&A, x, y, ri(-6, 6));
    }
    check_kernel_image(&A);
    rmat_clear(&A);
  }
  // NULL arguments
  {
    rmat_t A = {0}, H = {0};
    u64 p = 0;
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    assert(rmat_kernel_image(NULL, &H, &p) == RABIN_ERR_NULL_PTR);
    assert(rmat_kernel_image(&A, NULL, &p) == RABIN_ERR_NULL_PTR);
    assert(rmat_kernel_image(&A, &H, NULL) == RABIN_ERR_NULL_PTR);
    rmat_clear(&A);
  }
  printf("[PASS] rmat_kernel_image invariants\n");
}

