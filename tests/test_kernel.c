/* 2 x 3 matrix with kernel generated by (-1, -1, 1) */
static void build_dep_2x3(rmat_t* A)
{
  assert(rmat_init(A, 2, 3) == RABIN_SUCCESS);
  set164(A, 0, 0, 1);
  set164(A, 1, 0, 0);
  set164(A, 0, 1, 0);
  set164(A, 1, 1, 1);
  set164(A, 0, 2, 1);  // col 2 = col 0 + col 1
  set164(A, 1, 2, 1);
}

static void test_kernel_basic(void)
{
  rmat_t A = {0}, K = {0}, AK = {0}, Ke = {0};
  build_dep_2x3(&A);

  assert(rmat_kernel(&A, &K) == RABIN_SUCCESS);
  assert(K.rows == 3 && K.cols == 1);
  assert(rmat_init(&AK, A.rows, K.cols) == RABIN_SUCCESS);
  assert(rmat_mul(&AK, &A, &K) == RABIN_SUCCESS);
  assert(is_zero_mat(&AK));

  // the kernel lattice is exactly Z * (-1, -1, 1)
  assert(rmat_init(&Ke, 3, 1) == RABIN_SUCCESS);
  set164(&Ke, 0, 0, -1);
  set164(&Ke, 1, 0, -1);
  set164(&Ke, 2, 0, 1);
  assert(same_lattice(&K, &Ke));

  rmat_clear(&A);
  rmat_clear(&K);
  rmat_clear(&AK);
  rmat_clear(&Ke);
  printf("[PASS] rmat_kernel basic\n");
}

static void test_kernel_shapes(void)
{
  // zero matrix: whole Z^3
  {
    rmat_t A = {0}, K = {0}, I3 = {0};
    assert(rmat_init(&A, 2, 3) == RABIN_SUCCESS);
    assert(rmat_kernel(&A, &K) == RABIN_SUCCESS);
    assert(K.rows == 3 && K.cols == 3);
    assert(rmat_init(&I3, 3, 3) == RABIN_SUCCESS);
    assert(rmat_id(&I3, 3) == RABIN_SUCCESS);
    assert(same_lattice(&K, &I3));
    rmat_clear(&A);
    rmat_clear(&K);
    rmat_clear(&I3);
  }
  // full rank: empty kernel
  {
    rmat_t A = {0}, K = {0};
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    set164(&A, 0, 0, 2);
    set164(&A, 1, 1, 3);
    assert(rmat_kernel(&A, &K) == RABIN_SUCCESS);
    assert(K.rows == 2 && K.cols == 0);
    rmat_clear(&A);
    rmat_clear(&K);
  }
  // 1 x 1: [6] kills nothing, [0] is the whole Z
  {
    rmat_t A = {0}, K = {0};
    assert(rmat_init(&A, 1, 1) == RABIN_SUCCESS);
    set164(&A, 0, 0, 6);
    assert(rmat_kernel(&A, &K) == RABIN_SUCCESS);
    assert(K.cols == 0);
    rmat_clear(&K);
    assert(rmat_init(&K, 1, 1) == RABIN_SUCCESS);
    set164(&A, 0, 0, 0);
    assert(rmat_kernel(&A, &K) == RABIN_SUCCESS);
    assert(K.rows == 1 && K.cols == 1);
    assert(rz_is_eq_i64(RMAT_GET(&K, 0, 0), 1) ||
           rz_is_eq_i64(RMAT_GET(&K, 0, 0), -1));
    rmat_clear(&A);
    rmat_clear(&K);
  }
  // NULL arguments
  {
    rmat_t A = {0}, K = {0};
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    assert(rmat_kernel(NULL, &K) == RABIN_ERR_NULL_PTR);
    assert(rmat_kernel(&A, NULL) == RABIN_ERR_NULL_PTR);
    rmat_clear(&A);
  }
  printf("[PASS] rmat_kernel shapes / edges\n");
}

