// column with the smallest residual among columns whose trailing scaled
// entries vanish (genuine relations); returns false if none exists
static bool best_relation(const rmat_t* REL, const double* im,
                          const double* err, double* out, u64* col_out)
{
  const u64 n = REL->cols;
  const u64 tail0 = im ? n + 1 : n;
  const u64 ntail = REL->rows - tail0;
  bool found = false;
  double best = 0.0;
  for (u64 c = 0; c < n; c++) {
    bool ok = true;
    for (u64 t = 0; t < ntail; t++) {
      if (!rz_is_zero(RMAT_GET(REL, tail0 + t, c))) ok = false;
    }
    if (!ok) continue;
    if (!found || err[c] < best) {
      found = true;
      best = err[c];
      *col_out = c;
    }
  }
  *out = best;
  return found;
}

static void test_linear_dependence(void)
{
  // 1, sqrt(2), sqrt(2)+1 : relation (-1, -1, 1)
  {
    const double sq2 = sqrt(2.0);
    double re[3] = {1.0, sq2, sq2 + 1.0};
    double err[3] = {0.0, 0.0, 0.0};
    rmat_t REL = {0};
    assert(rmat_linear_dependence(re, NULL, 3, 1e6, &REL, err) ==
           RABIN_SUCCESS);
    double res = 0.0;
    u64 c = 0;
    assert(best_relation(&REL, NULL, err, &res, &c));
    assert(res < 1e-6);
    const i64 c0 = get_i64(RMAT_GET(&REL, 0, c));
    const i64 c1 = get_i64(RMAT_GET(&REL, 1, c));
    const i64 c2 = get_i64(RMAT_GET(&REL, 2, c));
    // primitive and (-1, -1, 1) up to sign
    assert((c0 == -1 && c1 == -1 && c2 == 1) ||
           (c0 == 1 && c1 == 1 && c2 == -1));
    rmat_clear(&REL);
  }
  // complex: 1, 1+i, -i : relation (-1, 1, 1)
  {
    double re[3] = {1.0, 1.0, 0.0};
    double im[3] = {0.0, 1.0, -1.0};
    double err[3] = {0.0, 0.0, 0.0};
    rmat_t REL = {0};
    assert(rmat_linear_dependence(re, im, 3, 1e6, &REL, err) == RABIN_SUCCESS);
    assert(REL.rows == 5);
    double res = 0.0;
    u64 c = 0;
    assert(best_relation(&REL, im, err, &res, &c));
    assert(res < 1e-6);
    const i64 c0 = get_i64(RMAT_GET(&REL, 0, c));
    const i64 c1 = get_i64(RMAT_GET(&REL, 1, c));
    const i64 c2 = get_i64(RMAT_GET(&REL, 2, c));
    assert((c0 == -1 && c1 == 1 && c2 == 1) ||
           (c0 == 1 && c1 == -1 && c2 == -1));
    rmat_clear(&REL);
  }
  // invalid arguments
  {
    double re[2] = {1.0, 2.0};
    rmat_t REL = {0};
    assert(rmat_linear_dependence(NULL, NULL, 2, 1.0, &REL, NULL) ==
           RABIN_ERR_NULL_PTR);
    assert(rmat_linear_dependence(re, NULL, 1, 1.0, &REL, NULL) ==
           RABIN_ERR_INVALID_ARG);
    assert(rmat_linear_dependence(re, NULL, 2, -1.0, &REL, NULL) ==
           RABIN_ERR_INVALID_ARG);
    assert(rmat_linear_dependence(re, NULL, 2, 0.0, &REL, NULL) ==
           RABIN_ERR_INVALID_ARG);
    const double inf = 1.0 / 0.0;
    double bad[3] = {1.0, 2.0, inf};
    assert(rmat_linear_dependence(bad, NULL, 3, 1e6, &REL, NULL) ==
           RABIN_ERR_INVALID_ARG);
  }
  printf("[PASS] rmat_linear_dependence\n");
}

static void test_algebraic_relation(void)
{
  // a = sqrt(2), degree 2 : x^2 - 2
  {
    rmat_t poly = {0};
    double err[3] = {0.0, 0.0, 0.0};
    assert(rmat_algebraic_relation(sqrt(2.0), 0.0, 2, 1e8, &poly, err) ==
           RABIN_SUCCESS);
    assert(poly.rows == 4 && poly.cols == 3);
    double res = 0.0;
    u64 c = 0;
    // trailing scaled entry must vanish for a genuine relation
    const u64 n = 3;
    bool found = false;
    for (u64 j = 0; j < n; j++) {
      if (!rz_is_zero(RMAT_GET(&poly, n, j))) continue;
      if (!found || err[j] < res) {
        found = true;
        res = err[j];
        c = j;
      }
    }
    assert(found);
    assert(res < 1e-6);
    const i64 c0 = get_i64(RMAT_GET(&poly, 0, c));
    const i64 c1 = get_i64(RMAT_GET(&poly, 1, c));
    const i64 c2 = get_i64(RMAT_GET(&poly, 2, c));
    assert((c0 == -2 && c1 == 0 && c2 == 1) ||
           (c0 == 2 && c1 == 0 && c2 == -1));
    rmat_clear(&poly);
  }
  // a = i, degree 2 : x^2 + 1
  {
    rmat_t poly = {0};
    double err[3] = {0.0, 0.0, 0.0};
    assert(rmat_algebraic_relation(0.0, 1.0, 2, 1e6, &poly, err) ==
           RABIN_SUCCESS);
    assert(poly.rows == 5 && poly.cols == 3);
    double res = 0.0;
    u64 c = 0;
    const u64 n = 3;
    bool found = false;
    for (u64 j = 0; j < n; j++) {
      if (!rz_is_zero(RMAT_GET(&poly, n, j)) ||
          !rz_is_zero(RMAT_GET(&poly, n + 1, j)))
        continue;
      if (!found || err[j] < res) {
        found = true;
        res = err[j];
        c = j;
      }
    }
    assert(found);
    assert(res < 1e-6);
    const i64 c0 = get_i64(RMAT_GET(&poly, 0, c));
    const i64 c1 = get_i64(RMAT_GET(&poly, 1, c));
    const i64 c2 = get_i64(RMAT_GET(&poly, 2, c));
    assert((c0 == 1 && c1 == 0 && c2 == 1) ||
           (c0 == -1 && c1 == 0 && c2 == -1));
    rmat_clear(&poly);
  }
  // invalid arguments
  {
    rmat_t poly = {0};
    assert(rmat_algebraic_relation(1.0, 0.0, 0, 1.0, &poly, NULL) ==
           RABIN_ERR_INVALID_ARG);
    assert(rmat_algebraic_relation(1.0, 0.0, 65, 1.0, &poly, NULL) ==
           RABIN_ERR_INVALID_ARG);
    assert(rmat_algebraic_relation(1.0, 0.0, 2, 0.0, &poly, NULL) ==
           RABIN_ERR_INVALID_ARG);
    const double inf = 1.0 / 0.0;
    assert(rmat_algebraic_relation(inf, 0.0, 2, 1e6, &poly, NULL) ==
           RABIN_ERR_INVALID_ARG);
    // overflow of the powers
    assert(rmat_algebraic_relation(1e200, 0.0, 4, 1e6, &poly, NULL) ==
           RABIN_ERR_INVALID_ARG);
    assert(rmat_algebraic_relation(2.0, 0.0, 2, 1.0, NULL, NULL) ==
           RABIN_ERR_NULL_PTR);
  }
  printf("[PASS] rmat_algebraic_relation\n");
}

int main(void)
{
  test_kernel_basic();
  test_kernel_shapes();
  test_kernel_lll();
  test_kernel_random();
  test_kernel_image();
  test_linear_dependence();
  test_algebraic_relation();

  double re[3] = {101.0, 203.0, 307.0};
  double err[3] = {0.0, 0.0, 0.0};
  rmat_t REL = {0};
  assert(rmat_linear_dependence(re, NULL, 3, 1e6, &REL, err) == RABIN_SUCCESS);
  double res = 0.0;
  u64 c = 0;
  assert(best_relation(&REL, NULL, err, &res, &c));
  assert(res < 1e-6);
  const i64 c0 = get_i64(RMAT_GET(&REL, 0, c));
  const i64 c1 = get_i64(RMAT_GET(&REL, 1, c));
  const i64 c2 = get_i64(RMAT_GET(&REL, 2, c));
  printf(
      "[INFO] Linear dependence relation for {%g, %g, %g}: (%lld)*%g + "
      "(%lld)*%g + (%lld)*%g = 0\n",
      re[0], re[1], re[2], (long long)c0, re[0], (long long)c1, re[1],
      (long long)c2, re[2]);

  rmat_clear(&REL);

  printf("All kernel/image/dependence tests passed\n");
  return 0;
}
