/*
 * Tests for the Cohen 2.7 applications: rmat_kernel(), rmat_kernel_lll(),
 * rmat_kernel_image(), rmat_linear_dependence(), rmat_algebraic_relation().
 *
 * Verified invariants:
 *   - A * K == 0 and K has n - rank(A) columns,
 *   - the kernel bases of rmat_kernel() and rmat_kernel_lll() generate the
 *     same lattice (comparison via HNF),
 *   - rmat_kernel_image() yields a unimodular H whose first columns are
 *     exactly the kernel and whose last columns preserve the image lattice,
 *   - dependence relations found for sqrt(2)-type inputs are exact, small,
 *     and primitive.
 */
#include <assert.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#include "../include/rmat.h"
#include "../include/rz.h"

/* ------------------------------------------------------------------ */
/* Small helpers                                                      */
/* ------------------------------------------------------------------ */

static void set164(rmat_t* M, u64 r, u64 c, i64 v)
{
  rz_t t;
  rz_init(&t);
  rz_set_i64(&t, v);
  assert(rmat_set(M, &t, r, c) == RABIN_SUCCESS);
  rz_clear(&t);
}

static i64 get_i64(const rz_t* z)
{
  assert(z->size <= 1);
  const i64 v = (i64)z->limbs[0];
  return z->is_neg ? -v : v;
}

static bool is_unimodular(const rmat_t* M)
{
  if (M->rows == 0 || M->cols == 0) return true;
  if (M->rows != M->cols) return false;
  rz_t det;
  rz_init(&det);
  assert(rmat_det(&det, M) == RABIN_SUCCESS);
  det.is_neg = false;
  bool ok = rz_is_eq_i64(&det, 1);
  rz_clear(&det);
  return ok;
}

static bool same_lattice(const rmat_t* A, const rmat_t* B)
{
  if (A->cols == 0 || B->cols == 0) return A->cols == B->cols;
  rmat_t HA = {0}, HB = {0};
  assert(rmat_hermite(&HA, A) == RABIN_SUCCESS);
  assert(rmat_hermite(&HB, B) == RABIN_SUCCESS);
  bool ok = (HA.cols == HB.cols) && rmat_equal(&HA, &HB);
  rmat_clear(&HA);
  rmat_clear(&HB);
  return ok;
}

static bool is_zero_mat(const rmat_t* M)
{
  for (u64 x = 0; x < M->rows; x++) {
    for (u64 y = 0; y < M->cols; y++) {
      if (!rz_is_zero(RMAT_GET(M, x, y))) return false;
    }
  }
  return true;
}

static u64 rank_via_mlll(const rmat_t* A)
{
  assert(A->rows <= A->cols);
  rmat_t B = {0}, H = {0};
  assert(rmat_init(&B, A->rows, A->cols) == RABIN_SUCCESS);
  assert(rmat_copy(&B, A) == RABIN_SUCCESS);
  u64 rank = 0;
  assert(rmat_mlll(&B, A->cols, 0.75, &H, &rank) == RABIN_SUCCESS);
  rmat_clear(&B);
  rmat_clear(&H);
  return rank;
}

static int ri(int lo, int hi) { return lo + rand() % (hi - lo + 1); }

