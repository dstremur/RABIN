static void test_kernel_lll(void)
{
  // dependent column in the middle: v0=(1,2,3), v1=2*v0, v2=(0,0,1)
  // kernel: {t * (-2, 1, 0)}
  {
    rmat_t A = {0}, K1 = {0}, K2 = {0}, Ke = {0};
    assert(rmat_init(&A, 3, 3) == RABIN_SUCCESS);
    set164(&A, 0, 0, 1);
    set164(&A, 1, 0, 2);
    set164(&A, 2, 0, 3);
    set164(&A, 0, 1, 2);
    set164(&A, 1, 1, 4);
    set164(&A, 2, 1, 6);
    set164(&A, 0, 2, 0);
    set164(&A, 1, 2, 0);
    set164(&A, 2, 2, 1);

    assert(rmat_kernel_lll(&A, &K2) == RABIN_SUCCESS);
    assert(K2.rows == 3 && K2.cols == 1);
    assert(rmat_kernel(&A, &K1) == RABIN_SUCCESS);
    assert(K1.rows == 3 && K1.cols == 1);
    assert(same_lattice(&K1, &K2));

    assert(rmat_init(&Ke, 3, 1) == RABIN_SUCCESS);
    set164(&Ke, 0, 0, 2);
    set164(&Ke, 1, 0, -1);
    set164(&Ke, 2, 0, 0);
    assert(same_lattice(&K2, &Ke));

    rmat_clear(&A);
    rmat_clear(&K1);
    rmat_clear(&K2);
    rmat_clear(&Ke);
  }
  // full rank and zero matrix
  {
    rmat_t A = {0}, K = {0};
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    set164(&A, 0, 0, 1);
    set164(&A, 1, 1, 1);
    assert(rmat_kernel_lll(&A, &K) == RABIN_SUCCESS);
    assert(K.cols == 0);
    rmat_clear(&K);
    assert(rmat_init(&A, 3, 4) == RABIN_SUCCESS);
    assert(rmat_kernel_lll(&A, &K) == RABIN_SUCCESS);
    assert(K.rows == 4 && K.cols == 4);
    rmat_clear(&A);
    rmat_clear(&K);
  }
  // NULL arguments
  {
    rmat_t A = {0}, K = {0};
    assert(rmat_init(&A, 2, 2) == RABIN_SUCCESS);
    assert(rmat_kernel_lll(NULL, &K) == RABIN_ERR_NULL_PTR);
    assert(rmat_kernel_lll(&A, NULL) == RABIN_ERR_NULL_PTR);
    rmat_clear(&A);
  }
  printf("[PASS] rmat_kernel_lll edges\n");
}

static void test_kernel_random(void)
{
  srand(0x2B78);
  for (int trial = 0; trial < 20; trial++) {
    rmat_t A = {0}, K1 = {0}, K2 = {0}, AK = {0};
    const u64 m = 3, n = 5;
    assert(rmat_init(&A, m, n) == RABIN_SUCCESS);
    for (u64 x = 0; x < m; x++) {
      for (u64 y = 0; y < n; y++) set164(&A, x, y, ri(-5, 5));
    }
    const u64 rank = rank_via_mlll(&A);

    assert(rmat_kernel(&A, &K1) == RABIN_SUCCESS);
    assert(rmat_kernel_lll(&A, &K2) == RABIN_SUCCESS);
    assert(K1.rows == n && K2.rows == n);
    assert(K1.cols == n - rank);
    assert(K2.cols == n - rank);
    if (K1.cols > 0) {
      assert(rmat_init(&AK, A.rows, K1.cols) == RABIN_SUCCESS);
      assert(rmat_mul(&AK, &A, &K1) == RABIN_SUCCESS);
      assert(is_zero_mat(&AK));
      assert(same_lattice(&K1, &K2));
      rmat_clear(&AK);
    }
    rmat_clear(&A);
    rmat_clear(&K1);
    rmat_clear(&K2);
  }
  printf("[PASS] random kernels agree between HNF and LLL routes\n");
}

